print('Ready. Embedding dim =', EMB_DIM)

# ==================== 2. TRAIN THE ACTION DETECTOR ====================
# Input  = "speaker: utterance"   (NOT assignee/task — those are only filled
#          in on ACTION rows, so using them leaks the label)
# Output = P(this utterance is a commitment)
from sklearn.model_selection import train_test_split
from sklearn.metrics import classification_report, roc_auc_score, confusion_matrix, ConfusionMatrixDisplay


def load(path):
    df = pd.read_csv(path)
    x = (df.speaker.fillna('unknown') + ': ' + df.text.fillna('')).tolist()
    y = df.label.astype(str).str.upper().eq('ACTION').astype(int).values
    return x, y


def embed(texts, tag):
    os.makedirs('/content/emb_cache', exist_ok=True)
    cache = f'/content/emb_cache/{tag}_all-MiniLM-L6-v2.npy'
    if os.path.exists(cache) and len(np.load(cache)) == len(texts):
        return np.load(cache)
    e = embedder.encode(texts, batch_size=256, convert_to_numpy=True,
                        normalize_embeddings=True, show_progress_bar=True).astype('float32')
    np.save(cache, e)
    return e


x_train, y_train = load('/content/train_utterances_balanced.csv')
x_test,  y_test  = load('/content/test_utterances_balanced.csv')
X_train, X_test  = embed(x_train, 'train'), embed(x_test, 'test')
print(f'{len(X_train):,} train / {len(X_test):,} test')

# validation comes out of TRAIN so the test set stays untouched until the end
X_fit, X_val, y_fit, y_val = train_test_split(
    X_train, y_train, test_size=0.15, stratify=y_train, random_state=42)

model = tf.keras.Sequential([
    tf.keras.layers.Input((EMB_DIM,)),
    tf.keras.layers.Dense(256, activation='relu'),
    tf.keras.layers.Dropout(0.3),
    tf.keras.layers.Dense(128, activation='relu'),
    tf.keras.layers.Dense(1, activation='sigmoid'),
])
model.compile('adam', 'binary_crossentropy', metrics=['accuracy'])
model.fit(X_fit, y_fit, validation_data=(X_val, y_val),
          epochs=30, batch_size=256, verbose=2,
          callbacks=[tf.keras.callbacks.EarlyStopping(patience=5, restore_best_weights=True)])

prob = model.predict(X_test, verbose=0).ravel()
print(classification_report(y_test, prob >= 0.5, target_names=['DIALOG', 'ACTION'], digits=4))
print('ROC-AUC:', round(roc_auc_score(y_test, prob), 4))

# Plot Confusion Matrix
cm = confusion_matrix(y_test, prob >= 0.5)
disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=['DIALOG', 'ACTION'])
disp.plot(cmap=plt.cm.Blues)
plt.title('Confusion Matrix')
plt.show()

