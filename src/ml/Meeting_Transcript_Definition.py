"""## 5. Extract Commitments from a New Transcript"""

import tensorflow as tf

def extract_commitments(transcript_path, threshold=0.9):
    """Extracts commitments (tasks, owners, due dates) from a given transcript."""
    # Load the trained action detector model
    loaded_model = tf.keras.models.load_model('/content/action_detector.keras')

    # Process the transcript
    turns = to_turns(read_transcript(transcript_path))

    # Clean up any numerical speaker names that might have been incorrectly parsed
    turns.loc[turns.speaker.str.match(r'^\d+(\.\d+)?$'), 'speaker'] = 'UNKNOWN'

    utts = to_utterances(turns)

    # Check if there are any utterances to process
    if utts.empty:
        print(f"No utterances found in {transcript_path}.")
        return pd.DataFrame(columns=['owner', 'task', 'due', 'prob'])

    # Embed utterances and predict probabilities
    utterance_embeddings = embedder.encode(
        (utts.speaker + ': ' + utts.text).tolist(),
        batch_size=128,
        convert_to_numpy=True,
        normalize_embeddings=True
    )
    utts['prob'] = loaded_model.predict(utterance_embeddings, verbose=0).ravel()

    # Filter for actions above the threshold
    actions = utts[utts.prob >= threshold].copy()

    if actions.empty:
        print(f"No commitments found above threshold {threshold} in {transcript_path}.")
        return pd.DataFrame(columns=['owner', 'task', 'due', 'prob'])

    # Determine the roster of speakers for owner assignment
    roster = set(turns.speaker) - {'UNKNOWN'}

    # Extract owner, task, and due date
    actions['owner'] = [owner_of(t, s, roster) for t, s in zip(actions.text, actions.speaker)]
    actions['task'] = actions.text.map(task_of)
    actions['due'] = actions.text.map(due_of)

    return actions[['owner', 'task', 'due', 'prob']]

