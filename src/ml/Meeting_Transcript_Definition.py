actions = utts[utts.prob >= THRESHOLD].copy()
actions['owner'] = [owner_of(t, s, roster) for t, s in zip(actions.text, actions.speaker)]
actions['task'] = actions.text.map(task_of)
actions['due'] = actions.text.map(due_of)

pd.set_option('display.max_colwidth', 90, 'display.width', 200)
print(f'{len(turns)} turns -> {len(utts)} utterances -> {len(actions)} commitments '
      f'(threshold {THRESHOLD})\n')
print(actions[['owner', 'task', 'due', 'prob']].to_string(index=False))
actions.to_csv('/content/commitments.csv', index=False)

